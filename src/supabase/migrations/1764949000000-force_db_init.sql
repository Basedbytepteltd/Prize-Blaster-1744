-- 1. Create app_settings table (Safe create)
CREATE TABLE IF NOT EXISTS public.app_settings (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  config jsonb NOT NULL DEFAULT '{}'::jsonb,
  updated_at timestamptz DEFAULT now()
);

ALTER TABLE public.app_settings ENABLE ROW LEVEL SECURITY;

-- Policies for app_settings (Drop and Recreate to be safe)
DROP POLICY IF EXISTS "Allow public read access" ON public.app_settings;
CREATE POLICY "Allow public read access" ON public.app_settings FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow public update access" ON public.app_settings;
CREATE POLICY "Allow public update access" ON public.app_settings FOR UPDATE USING (true);

DROP POLICY IF EXISTS "Allow public insert access" ON public.app_settings;
CREATE POLICY "Allow public insert access" ON public.app_settings FOR INSERT WITH CHECK (true);

-- 2. Create withdrawals table (Safe create)
CREATE TABLE IF NOT EXISTS public.withdrawals (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  email text NOT NULL,
  gcash_number text NOT NULL,
  amount_php numeric NOT NULL,
  points_redeemed numeric NOT NULL,
  status text DEFAULT 'pending',
  created_at timestamptz DEFAULT now()
);

ALTER TABLE public.withdrawals ENABLE ROW LEVEL SECURITY;

-- Policies for withdrawals
DROP POLICY IF EXISTS "Allow public insert to withdrawals" ON public.withdrawals;
CREATE POLICY "Allow public insert to withdrawals" ON public.withdrawals FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public read withdrawals" ON public.withdrawals;
CREATE POLICY "Allow public read withdrawals" ON public.withdrawals FOR SELECT USING (true);

