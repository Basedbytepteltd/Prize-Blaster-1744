# Fix App Settings and Permissions
1. **Ensures Table Exists**: Creates `app_settings` if missing.
2. **Security**: Enables RLS and forces public read access (fixes 404/permission errors).
3. **Seed Data**: Inserts default config if the table is empty.
*/

-- 1. Safe Table Creation
CREATE TABLE IF NOT EXISTS public.app_settings (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    config jsonb NOT NULL DEFAULT '{}'::jsonb,
    updated_at timestamptz DEFAULT now()
);

-- 2. Enable RLS
ALTER TABLE public.app_settings ENABLE ROW LEVEL SECURITY;

-- 3. Idempotent Policies (Drop then Create to avoid conflicts)
DO $$ 
BEGIN
    -- Read Policy
    DROP POLICY IF EXISTS "Allow public read access" ON public.app_settings;
    CREATE POLICY "Allow public read access" ON public.app_settings FOR SELECT USING (true);
    
    -- Insert Policy
    DROP POLICY IF EXISTS "Allow public insert access" ON public.app_settings;
    CREATE POLICY "Allow public insert access" ON public.app_settings FOR INSERT WITH CHECK (true);
    
    -- Update Policy
    DROP POLICY IF EXISTS "Allow public update access" ON public.app_settings;
    CREATE POLICY "Allow public update access" ON public.app_settings FOR UPDATE USING (true);
END $$;

