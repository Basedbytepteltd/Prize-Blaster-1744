/*
# Fix Schema and Seed Data

This migration ensures all necessary tables exist and are populated with default data. It uses `IF NOT EXISTS` to be safe to run even if partial tables exist.

1.  **Tables**
    -   `app_settings`: Stores game configuration (eCPM, withdrawal limits, etc.).
    -   `withdrawals`: Stores user payout requests.

2.  **Security**
    -   Enables Row Level Security (RLS) on all tables.
    -   Adds policies for public read/write access (for this demo application).

3.  **Seeding**
    -   Populates `app_settings` with default values if empty.
*/

-- 1. Create app_settings table
CREATE TABLE IF NOT EXISTS app_settings (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    config jsonb NOT NULL,
    updated_at timestamptz DEFAULT now()
);

ALTER TABLE app_settings ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'app_settings' AND policyname = 'Allow public read access') THEN
        CREATE POLICY "Allow public read access" ON app_settings FOR SELECT USING (true);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'app_settings' AND policyname = 'Allow public update access') THEN
        CREATE POLICY "Allow public update access" ON app_settings FOR UPDATE USING (true);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'app_settings' AND policyname = 'Allow public insert access') THEN
        CREATE POLICY "Allow public insert access" ON app_settings FOR INSERT WITH CHECK (true);
    END IF;
END $$;

-- 2. Create withdrawals table
CREATE TABLE IF NOT EXISTS withdrawals (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    email text NOT NULL,
    gcash_number text NOT NULL,
    amount_php numeric NOT NULL,
    points_redeemed numeric NOT NULL,
    status text DEFAULT 'pending',
    created_at timestamptz DEFAULT now()
);

ALTER TABLE withdrawals ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'withdrawals' AND policyname = 'Allow public insert to withdrawals') THEN
        CREATE POLICY "Allow public insert to withdrawals" ON withdrawals FOR INSERT WITH CHECK (true);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE tablename = 'withdrawals' AND policyname = 'Allow public read withdrawals') THEN
        CREATE POLICY "Allow public read withdrawals" ON withdrawals FOR SELECT USING (true);
    END IF;
END $$;

