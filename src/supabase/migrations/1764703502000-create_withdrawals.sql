/*
# Create Withdrawals Table for Payout Requests

1.  **New Tables**
    -   `withdrawals`
        -   `id` (bigint, primary key)
        -   `email` (text) - The user's email for notification
        -   `gcash_number` (text) - The target wallet number
        -   `amount_php` (numeric) - Amount in Peso
        -   `points_redeemed` (numeric) - Points spent
        -   `status` (text) - Status of the request (pending, paid, rejected)
        -   `created_at` (timestamptz)

2.  **Security**
    -   Enable RLS
    -   Allow public insert (for demo purposes)
*/
CREATE TABLE IF NOT EXISTS withdrawals (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    email text NOT NULL,
    gcash_number text NOT NULL,
    amount_php numeric NOT NULL,
    points_redeemed numeric NOT NULL,
    status text DEFAULT 'pending',
    created_at timestamptz DEFAULT now()
);

ALTER TABLE withdrawals ENABLE ROW LEVEL SECURITY;

-- Allow users to submit withdrawal requests
CREATE POLICY "Allow public insert to withdrawals" ON withdrawals
FOR INSERT
WITH CHECK (true);

-- Allow admins (or public for demo) to view requests
CREATE POLICY "Allow public read withdrawals" ON withdrawals
FOR SELECT
USING (true);