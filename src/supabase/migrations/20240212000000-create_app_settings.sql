/*
# Create App Settings Table

1.  **New Tables**
    -   `app_settings`
        -   `id` (bigint, primary key)
        -   `config` (jsonb, stores the entire app configuration)
        -   `updated_at` (timestamptz)

2.  **Security**
    -   Enable RLS on `app_settings`
    -   Add policies for read/write access (secured via app logic for this demo)
*/
CREATE TABLE IF NOT EXISTS app_settings (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    config jsonb NOT NULL,
    updated_at timestamptz DEFAULT now()
);

ALTER TABLE app_settings ENABLE ROW LEVEL SECURITY;

-- Allow anyone to read the config (needed for the app to know ad rates)
CREATE POLICY "Allow public read access" ON app_settings
FOR SELECT
USING (true);

-- Allow updates (In a production app, restrict this to authenticated admins only)
CREATE POLICY "Allow public update access" ON app_settings
FOR UPDATE
USING (true);

CREATE POLICY "Allow public insert access" ON app_settings
FOR INSERT
WITH CHECK (true);